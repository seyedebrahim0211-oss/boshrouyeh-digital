<?php
/**
 * Keeps the Khesht icon set identical across the theme, core plugin and Flutter app.
 * Source of truth: wordpress/themes/boshrouyeh-khesht/inc/icon-set.php
 * Usage: php bin/sync-icons.php [--check]
 */
define( 'ABSPATH', __DIR__ );
$root  = dirname( __DIR__ );
$src   = $root . '/wordpress/themes/boshrouyeh-khesht/inc/icon-set.php';
$icons = require $src;
$check = in_array( '--check', $argv, true );
$fail  = false;

$core = $root . '/wordpress/plugins/boshrouyeh-core/includes/icon-set.php';
$want = str_replace( '@package BoshrouyehKhesht', '@package BoshrouyehCore', file_get_contents( $src ) );
if ( ! file_exists( $core ) || file_get_contents( $core ) !== $want ) {
	$fail = true;
	if ( ! $check ) { file_put_contents( $core, $want ); }
}

$dart = "// GENERATED by bin/sync-icons.php — do not edit.\n// Khesht line icons (24×24, stroke 1.75).\n\nconst Map<String, String> kheshtIconPaths = {\n";
foreach ( $icons as $k => $v ) {
	$dart .= "  '" . $k . "': '" . str_replace( array( '\\', "'", '$' ), array( '\\\\', "\\'", '\\$' ), $v ) . "',\n";
}
$dart .= "};\n";
$df = $root . '/app/lib/core/khesht_icons_data.dart';
if ( ! file_exists( $df ) || file_get_contents( $df ) !== $dart ) {
	$fail = true;
	if ( ! $check ) { @mkdir( dirname( $df ), 0777, true ); file_put_contents( $df, $dart ); }
}
if ( $check && $fail ) { fwrite( STDERR, "Icon sets are out of sync. Run: php bin/sync-icons.php\n" ); exit( 1 ); }
echo $check ? "Icon sets in sync.\n" : "Icons synced (" . count( $icons ) . ").\n";
